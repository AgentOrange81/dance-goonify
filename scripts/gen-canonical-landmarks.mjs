/**
 * Generate lib/face/canonical.ts — a normalized 478-pt MediaPipe FaceLandmarker
 * mesh used by synthesizeFaceLandmarks() to project a face into any
 * (cx, cy, rx, ry, rotation) frame.
 *
 * Reads the first (face-on) keyframe of the plate-06 (H4) warp-front scene
 * directly from lib/scenes.ts, normalizes to [-1, 1] in both axes, and writes
 * the canonical array out.
 *
 * Run after a major landmark measurement update against plate 06:
 *   pnpm measure-keyframes
 *   node scripts/gen-canonical-landmarks.mjs
 */

import fs from 'node:fs'

const SCENES = fs.readFileSync('lib/scenes.ts', 'utf8')

// Locate the warp-front scene (plate 06 reference) and its first keyframe.
const start = SCENES.indexOf("id: 'club-h4-front-grind'")
const end = SCENES.indexOf("id: 'club-h4-side-grind'")
if (start < 0 || end < 0) {
  console.error("Couldn't find warp-front scene in lib/scenes.ts — bailing.")
  process.exit(1)
}
const block = SCENES.slice(start, end)
const m = block.match(/\{ t: 0\.000, cx: ([\d.\-]+), cy: ([\d.\-]+), rx: ([\d.\-]+), ry: ([\d.\-]+), rotation: ([\d.\-]+), headYaw: ([\d.\-]+), landmarks: \[([\s\S]*?)\] \}/)
if (!m) {
  console.error("Couldn't parse first keyframe of warp-front scene.")
  process.exit(1)
}

const cx = +m[1], cy = +m[2], rx = +m[3], ry = +m[4], rotation = +m[5]
const lmStr = m[7]
const re2 = /\{x: ([\d.\-]+), y: ([\d.\-]+)\}/g
const landmarks = []
let mm
while ((mm = re2.exec(lmStr)) !== null) {
  landmarks.push({ x: +mm[1], y: +mm[2] })
}
if (landmarks.length !== 478) {
  console.error(`Expected 478 landmarks in warp-front frame 0, got ${landmarks.length}`)
  process.exit(1)
}

const rot = (rotation * Math.PI) / 180
const cosR = Math.cos(rot)
const sinR = Math.sin(rot)

// Unrotate + untranslate + unscale to canonical space.
const raw = landmarks.map(lm => {
  const dx = lm.x - cx
  const dy = lm.y - cy
  const xr = cosR * dx + sinR * dy
  const yr = -sinR * dx + cosR * dy
  return { x: xr / rx, y: yr / ry }
})

// Normalize to [-1, 1] in both axes so per-axis (rx, ry) scaling in
// synthesizeFaceLandmarks() lands the mesh exactly on the destination oval.
const xMax = Math.max(...raw.map(p => Math.abs(p.x)))
const yMax = Math.max(...raw.map(p => Math.abs(p.y)))
const canonical = raw.map(p => ({ x: p.x / xMax, y: p.y / yMax }))

const xMin = Math.min(...canonical.map(p => p.x)).toFixed(3)
const xMaxStr = Math.max(...canonical.map(p => p.x)).toFixed(3)
const yMin = Math.min(...canonical.map(p => p.y)).toFixed(3)
const yMaxStr = Math.max(...canonical.map(p => p.y)).toFixed(3)

const ts = `// AUTO-GENERATED by scripts/gen-canonical-landmarks.mjs — do not hand-edit.
// Source: 478-point MediaPipe FaceLandmarker mesh, measured against the
// plate-06 (H4 cel-shaded) front face-on reference frame
//   cx=${cx} cy=${cy} rx=${rx} ry=${ry} rotation=${rotation}
// then normalized to (0,0) origin, rotated by -rotation, and re-scaled to
// [-1, 1] in both x and y so per-axis (rx, ry) scaling in
// synthesizeFaceLandmarks() lands the face mesh exactly on the destination
// oval boundary in both dimensions.
// Original bounds: x ∈ [${xMin}, ${xMaxStr}], y ∈ [${yMin}, ${yMaxStr}]
// Normalized bounds: [-1, 1] in both axes (max abs = 1.0)
// The aspect ratio of the canonical mesh is preserved in the normalized
// form; per-axis scaling in the destination stretches the face to match the
// oval aspect. Acceptable for blankface scenes since the patch oval tracks the
// dancer position regardless.

export const CANONICAL_FACE_LANDMARKS: ReadonlyArray<{readonly x: number; readonly y: number}> = [
${canonical.map(p => `  { x: ${p.x.toFixed(4)}, y: ${p.y.toFixed(4)} }`).join(',\n')}
]
`

fs.writeFileSync('lib/face/canonical.ts', ts)
console.log(`wrote lib/face/canonical.ts (${ts.length} bytes, ${canonical.length} landmarks)`)